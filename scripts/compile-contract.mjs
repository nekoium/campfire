// One-off script: compiles CampfireCommunity.sol and writes the bytecode
// and ABI to src/contract-deployment.ts so the frontend can deploy the
// contract via wagmi's useDeployContract hook.
//
// Usage: node scripts/compile-contract.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import solc from "solc";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const sourcePath = join(root, "contracts", "CampfireCommunity.sol");
const source = readFileSync(sourcePath, "utf8");

// Solidity file doesn't use any imports, so a single-file compilation works.
const input = {
  language: "Solidity",
  sources: {
    "CampfireCommunity.sol": { content: source },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

if (output.errors) {
  const hasError = output.errors.some((e) => e.severity === "error");
  for (const e of output.errors) {
    console.log(`[${e.severity}] ${e.message}`);
  }
  if (hasError) {
    process.exit(1);
  }
}

const contract = output.contracts["CampfireCommunity.sol"]["CampfireCommunity"];
const abi = contract.abi;
const bytecode = "0x" + contract.evm.bytecode.object;

if (bytecode === "0x") {
  console.error("Compilation succeeded but bytecode is empty.");
  process.exit(1);
}

const outPath = join(root, "src", "contract-deployment.ts");
const content = `// AUTO-GENERATED by scripts/compile-contract.mjs — do not edit by hand.
// Run \`node scripts/compile-contract.mjs\` after changing CampfireCommunity.sol.

export const campfireBytecode = "${bytecode}" as const;

export const campfireDeployAbi = ${JSON.stringify(abi, null, 2)} as const;

export const campfireConstructorArgs = [
  "Campfire",
  "A shared ledger for mutual aid — record help, claim work, settle in local credits.",
] as const;
`;

writeFileSync(outPath, content, "utf8");

console.log(`Compiled successfully.`);
console.log(`  Bytecode length: ${bytecode.length} chars`);
console.log(`  ABI entries: ${abi.length}`);
console.log(`  Written to: src/contract-deployment.ts`);
